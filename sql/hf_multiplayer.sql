create or replace function fn_hf_end_turn(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_cur int; v_next text; v_next_seat int;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.status <> 'ACTIVE' or v_row.game_phase <> 'TURN_BASED' then raise exception 'No es fase por turnos'; end if;
  if v_row.active_player <> p_player and v_row.host_id <> p_player then raise exception 'No es tu turno'; end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  select (e->>'seat')::int into v_cur from jsonb_array_elements(v_players) e where e->>'player_id' = v_row.active_player limit 1;
  select e->>'player_id', (e->>'seat')::int into v_next, v_next_seat
    from jsonb_array_elements(v_players) e where (e->>'seat')::int > coalesce(v_cur, 0)
    order by (e->>'seat')::int limit 1;
  if v_next is null then
    select e->>'player_id', (e->>'seat')::int into v_next, v_next_seat
      from jsonb_array_elements(v_players) e order by (e->>'seat')::int limit 1;
    update hf_online_matches set active_player = v_next, current_turn = current_turn + 1,
      turn_started_at = now(), updated_at = now() where id = v_row.id returning * into v_row;
  else
    update hf_online_matches set active_player = v_next, turn_started_at = now(), updated_at = now()
      where id = v_row.id returning * into v_row;
  end if;
  return to_jsonb(v_row);
end $$;

create or replace function fn_hf_claim_host(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_seen timestamptz;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.host_id = p_player then return to_jsonb(v_row); end if;
  if hf_player_index(coalesce(v_row.players_data, '[]'::jsonb), p_player) < 0 then
    raise exception 'No estás en la sala';
  end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  select (e->>'last_seen')::timestamptz into v_seen
    from jsonb_array_elements(v_players) e where e->>'player_id' = v_row.host_id limit 1;
  if v_seen is not null and v_seen > now() - interval '20 seconds' then
    raise exception 'El anfitrión sigue conectado';
  end if;
  v_players := (select coalesce(jsonb_agg(
      case when e->>'player_id' = v_row.host_id then e || '{"is_bot": true}'::jsonb else e end), '[]'::jsonb)
    from jsonb_array_elements(v_players) e);
  update hf_online_matches set host_id = p_player, players_data = v_players, updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

