  return to_jsonb(v_row);
end $$;

-- Salir de la sala mientras está en espera.
create or replace function fn_hf_leave_room(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.status = 'ACTIVE' then raise exception 'No puedes salir de una partida activa'; end if;
  v_players := (select coalesce(jsonb_agg(e), '[]'::jsonb)
                from jsonb_array_elements(coalesce(v_row.players_data, '[]'::jsonb)) e
                where e->>'player_id' <> p_player);
  update hf_online_matches set players_data = v_players, updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

