-- ---------- utilidades ----------
create or replace function hf_jsonb_players(p jsonb)
returns jsonb language sql immutable as $$ select coalesce(p, '[]'::jsonb) $$;

create or replace function hf_player_index(p_players jsonb, p_player text)
returns int language sql immutable as $$
  select coalesce((
    select (ord - 1)::int
    from jsonb_array_elements(coalesce(p_players, '[]'::jsonb)) with ordinality as t(e, ord)
    where e->>'player_id' = p_player limit 1
  ), -1)
$$;

-- Crea una sala. p_setup: {mode, seed, size, n, biome, fog, difficulty, goal}
create or replace function fn_hf_create_room(
  p_room text, p_player text, p_name text, p_crest text, p_color text,
  p_setup jsonb default '{}'::jsonb, p_max int default 4
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches;
begin
  insert into hf_online_matches(room_code, host_id, status, max_players, setup_json, players_data)
  values (
    upper(trim(p_room)), p_player, 'WAITING', greatest(2, least(4, coalesce(p_max, 4))),
    coalesce(p_setup, '{}'::jsonb),
    jsonb_build_array(jsonb_build_object(
      'player_id', p_player, 'name', coalesce(p_name, 'Jugador'),
      'crest', coalesce(p_crest, 'c01'), 'color_hex', coalesce(p_color, '#3b82f6'),
      'seat', 1, 'time_bank_seconds', 210, 'is_ready', false, 'is_bot', false, 'last_seen', now()
    ))
  ) returning * into v_row;
  return to_jsonb(v_row);
exception when unique_violation then
  raise exception 'Esa sala ya existe';
end $$;

-- Une a un jugador. Si se llena, la sala pasa a ACTIVE en fase SIMULTANEOUS.
create or replace function fn_hf_join_room(
  p_room text, p_player text, p_name text, p_crest text, p_color text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_n int; v_i int;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.status = 'FINISHED' then raise exception 'Partida terminada'; end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  v_i := hf_player_index(v_players, p_player);
  if v_i >= 0 then return to_jsonb(v_row); end if;
  if v_row.status = 'ACTIVE' then raise exception 'La partida ya empezó'; end if;
  v_n := jsonb_array_length(v_players);
  if v_n >= v_row.max_players then raise exception 'Sala llena'; end if;
  v_players := v_players || jsonb_build_array(jsonb_build_object(
    'player_id', p_player, 'name', coalesce(p_name, 'Jugador'),
    'crest', coalesce(p_crest, 'c01'), 'color_hex', coalesce(p_color, '#3b82f6'),
    'seat', v_n + 1, 'time_bank_seconds', 210, 'is_ready', false, 'is_bot', false, 'last_seen', now()
  ));
  update hf_online_matches set
    players_data = v_players,
    status = case when v_n + 1 >= max_players then 'ACTIVE' else status end,
    game_phase = case when v_n + 1 >= max_players then 'SIMULTANEOUS' else game_phase end,
    turn_started_at = case when v_n + 1 >= max_players then now() else turn_started_at end,
    updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- El anfitrión arranca con 2+ jugadores (si no se llenó sola).
create or replace function fn_hf_start_room(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.host_id <> p_player then raise exception 'Solo el anfitrión puede iniciar'; end if;
  if jsonb_array_length(coalesce(v_row.players_data, '[]'::jsonb)) < 2 then raise exception 'Faltan jugadores'; end if;
  update hf_online_matches set status = 'ACTIVE', game_phase = 'SIMULTANEOUS',
    active_player = (players_data->0->>'player_id'), turn_started_at = now(), updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- Marca "listo". En SIMULTANEOUS, cuando todos lo están, avanza el turno.
create or replace function fn_hf_set_player_ready(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_i int; v_pending int;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  v_i := hf_player_index(v_players, p_player);
  if v_i < 0 then raise exception 'No estás en la sala'; end if;
  v_players := jsonb_set(v_players, array[v_i::text, 'is_ready'], 'true'::jsonb, true);
  if v_row.status = 'ACTIVE' and v_row.game_phase = 'SIMULTANEOUS' then
    select count(*) into v_pending
    from jsonb_array_elements(v_players) e
    where coalesce((e->>'is_ready')::boolean, false) = false
      and coalesce((e->>'is_bot')::boolean, false) = false;
    if v_pending = 0 then
      v_players := (select coalesce(jsonb_agg(e || jsonb_build_object('is_ready', false)), '[]'::jsonb)
                    from jsonb_array_elements(v_players) e);
      update hf_online_matches set players_data = v_players,
        current_turn = current_turn + 1, turn_started_at = now(), updated_at = now()
      where id = v_row.id returning * into v_row;
      return to_jsonb(v_row);
    end if;
  end if;
  update hf_online_matches set players_data = v_players, updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- Registra una acción (validada por el cliente anfitrión) y, en TURN_BASED,
-- suma +3 s al banco del jugador activo.
create or replace function fn_hf_submit_action(p_room text, p_player text, p_action jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_i int; v_seat int;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if v_row.status <> 'ACTIVE' then raise exception 'La partida no está activa'; end if;
  if v_row.game_phase = 'TURN_BASED' and v_row.active_player <> p_player then
    raise exception 'No es tu turno';
  end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  v_i := hf_player_index(v_players, p_player);
  if v_i < 0 then raise exception 'No estás en la sala'; end if;
  v_seat := coalesce((v_players->v_i->>'seat')::int, v_i + 1);
  if v_row.game_phase = 'TURN_BASED' then
    v_players := jsonb_set(v_players, array[v_i::text, 'time_bank_seconds'],
      to_jsonb(greatest(0, coalesce((v_players->v_i->>'time_bank_seconds')::int, 0) + 3)), true);
  end if;
  update hf_online_matches set
    players_data = v_players,
    actions = coalesce(actions, '[]'::jsonb) || jsonb_build_array(jsonb_build_object(
      'turn', v_row.current_turn, 'seat', v_seat, 'player_id', p_player,
      'action', coalesce(p_action, '{}'::jsonb), 'ts', now())),
    updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- Primer contacto: la partida pasa a turnos individuales.
create or replace function fn_hf_set_phase(p_room text, p_player text, p_phase text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_next text;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  if hf_player_index(coalesce(v_row.players_data, '[]'::jsonb), p_player) < 0 then
    raise exception 'No estás en la sala';
  end if;
  if p_phase = 'TURN_BASED' then
    v_next := coalesce(v_row.active_player, v_row.players_data->0->>'player_id');
    if v_next = p_player then
      v_next := coalesce(v_row.players_data->1->>'player_id', v_next);
    end if;
  end if;
  update hf_online_matches set game_phase = coalesce(p_phase, game_phase),
    active_player = coalesce(v_next, active_player), turn_started_at = now(), updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- Reloj agotado: el jugador pasa a bot y se cede el turno.
create or replace function fn_hf_timeout(p_room text, p_player text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_row hf_online_matches; v_players jsonb; v_i int; v_next text;
begin
  select * into v_row from hf_online_matches where room_code = upper(trim(p_room)) for update;
  if not found then raise exception 'Sala no encontrada'; end if;
  v_players := coalesce(v_row.players_data, '[]'::jsonb);
  v_i := hf_player_index(v_players, p_player);
  if v_i < 0 then raise exception 'No estás en la sala'; end if;
  v_players := jsonb_set(v_players, array[v_i::text, 'is_bot'], 'true'::jsonb, true);
  v_players := jsonb_set(v_players, array[v_i::text, 'time_bank_seconds'], '0'::jsonb, true);
  select e->>'player_id' into v_next
  from jsonb_array_elements(v_players) e
  where e->>'player_id' <> p_player order by (e->>'seat')::int limit 1;
  update hf_online_matches set players_data = v_players,
    active_player = coalesce(v_next, active_player), turn_started_at = now(), updated_at = now()
  where id = v_row.id returning * into v_row;
  return to_jsonb(v_row);
end $$;

-- Late para presencia (no saca al jugador de la partida).
